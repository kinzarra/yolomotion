#!/usr/bin/env node
// Word timings for a synthesised voiceover, from macOS Speech.framework —
// on-device, free. Writes the generated `src/templates/<id>/asr.ts`, which
// the template passes to defineVoiceover(DURATIONS, lines, ASR) so its
// karaoke captions follow the real voice instead of a letter-weight estimate.
//
//   node scripts/gen-asr.mjs scripts/voiceover/<id>.json [--locale ru-RU]
//
// Needs the Transcribe.app bundle described in scripts/transcribe.swift
// (TRANSCRIBE_APP, default /tmp/Transcribe.app). Never edit asr.ts by hand:
// re-run this after every re-voice.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, "..");
const argv = process.argv.slice(2);
const manifestArg = argv.find((a) => !a.startsWith("--"));
if (!manifestArg) {
  console.error("usage: node scripts/gen-asr.mjs scripts/voiceover/<id>.json [--locale ru-RU]");
  process.exit(1);
}
const locale = argv.includes("--locale") ? argv[argv.indexOf("--locale") + 1] : "ru-RU";
const app = process.env.TRANSCRIBE_APP || "/tmp/Transcribe.app";
if (!fs.existsSync(path.join(app, "Contents/MacOS/transcribe"))) {
  console.error(`No ${app}. Build it as described at the top of scripts/transcribe.swift.`);
  process.exit(1);
}

const manifestPath = path.resolve(pkg, manifestArg);
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const outDir = path.resolve(pkg, manifest.outDir);
const id = path.basename(outDir);
const work = fs.mkdtempSync(path.join(os.tmpdir(), `asr-${id}-`));

const sleep = (ms) => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);

const result = {};
for (const [clip] of manifest.lines) {
  const mp3 = path.join(outDir, `${clip}.mp3`);
  if (!fs.existsSync(mp3)) {
    console.warn(`skip ${clip}: no ${mp3}`);
    continue;
  }
  const wav = path.join(work, `${clip}.wav`);
  const json = path.join(work, `${clip}.json`);
  execFileSync("ffmpeg", ["-v", "error", "-y", "-i", mp3, "-ar", "16000", "-ac", "1", wav]);
  // `open` gives the bundle its TCC identity; the answer comes back as a file.
  execFileSync("open", [app, "--args", wav, json, locale]);
  for (let i = 0; i < 120 && !(fs.existsSync(json) && fs.statSync(json).size > 0); i += 1) sleep(500);
  if (!fs.existsSync(json)) throw new Error(`ASR timed out on ${clip}`);
  sleep(200);
  const data = JSON.parse(fs.readFileSync(json, "utf8"));
  result[clip] = (data.segments ?? []).map((s) => ({
    text: s.text,
    start: Math.round(s.start * 1000) / 1000,
    end: Math.round((s.start + s.duration) * 1000) / 1000,
  }));
  console.log(`${clip}: ${result[clip].map((w) => `${w.text}@${w.start}`).join(" ")}`);
}

const target = path.join(pkg, "src/templates", id, "asr.ts");
const body =
  `// Generated by scripts/gen-asr.mjs — do not edit by hand.\n` +
  `// Word timings (raw seconds into each clip, before VO_RATE) from macOS\n` +
  `// Speech.framework (${locale}). Regenerate after every re-voice:\n` +
  `//   node scripts/gen-asr.mjs ${path.relative(pkg, manifestPath)}\n` +
  `import type { AsrWord } from "../../reel";\n\n` +
  `export const ASR: Record<string, AsrWord[]> = ${JSON.stringify(result, null, 2)};\n`;
fs.writeFileSync(target, body);
console.log(`→ ${path.relative(process.cwd(), target)}`);
