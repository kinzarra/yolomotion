#!/usr/bin/env python3
# Word timings for a synthesised voiceover with faster-whisper (local, free,
# Linux/cloud twin of gen-asr.mjs, which needs macOS Speech.framework).
# Writes the generated src/templates/<id>/asr.ts for defineVoiceover(…, ASR).
#
#   python3 scripts/gen-asr-whisper.py scripts/voiceover/<id>.json [--model small]
import json, os, subprocess, sys
import numpy as np
from difflib import SequenceMatcher
import re
from faster_whisper import WhisperModel

manifest_path = sys.argv[1]
model_name = sys.argv[sys.argv.index("--model") + 1] if "--model" in sys.argv else "small"
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
m = json.load(open(os.path.join(root, manifest_path)))
out_dir = os.path.join(root, m["outDir"])
tid = os.path.basename(m["outDir"].rstrip("/"))
model = WhisperModel(model_name, device="cpu", compute_type="int8")
asr = {}
for name, text in m["lines"]:
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", os.path.join(out_dir, f"{name}.mp3"), "-f", "f32le", "-ac", "1", "-ar", "16000", "-"], capture_output=True, check=True).stdout
    segs, _ = model.transcribe(np.frombuffer(pcm, np.float32), language=m.get("languageCode", "ru"), word_timestamps=True, initial_prompt=text, vad_filter=False)
    words = [{"text": w.word.strip(), "start": round(w.start, 3), "end": round(w.end, 3)} for s in segs for w in s.words]
    heard = " ".join(w["text"] for w in words)
    norm = lambda t: re.sub(r"[^а-яёa-z0-9 ]", "", t.lower().replace("\u0301", ""))
    sim = SequenceMatcher(None, norm(heard), norm(text)).ratio()
    # a hallucinated transcript would pin the karaoke to the wrong words: drop it, the letter weights take over
    if sim >= 0.8:
        asr[name] = words
    print(f"{name} sim={sim:.2f}{'' if sim >= 0.8 else ' DROPPED'} {heard}", flush=True)
dst = os.path.join(root, "src/templates", tid, "asr.ts")
with open(dst, "w") as f:
    f.write("// Generated by scripts/gen-asr-whisper.py — do not edit by hand.\n")
    f.write(f"// Regenerate: python3 scripts/gen-asr-whisper.py {manifest_path}\n")
    f.write('import type { AsrWord } from "../../reel/timeline";\n')
    f.write("export const ASR: Record<string, AsrWord[]> = " + json.dumps(asr, ensure_ascii=False, indent=1) + ";\n")
print("wrote", dst)
