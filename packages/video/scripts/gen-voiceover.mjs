// Generic ElevenLabs voiceover synthesis.
//   node scripts/gen-voiceover.mjs scripts/voiceover/<manifest>.json [env-path]
//                                  [--durations-only]
// The manifest carries voiceId, model, voice settings and the [name, text] lines;
// each line becomes `<outDir>/<name>.mp3` so a template can Sequence them by name.
//
// After synthesis every clip is measured with ffprobe and the durations are
// written to a generated `durations.ts` beside the template. Caption timing is
// computed from those numbers, and transcribing them by hand was the one step
// in the pipeline that silently produced drifting captions when a line was
// re-recorded. `--durations-only` re-measures existing mp3s without spending
// TTS credits (and without changing the audio).
import { mkdir, readFile, rename, unlink, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import path from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const run = promisify(execFile);

// ElevenLabs returns each line at its own level; without this the voiceover
// wanders 3dB between scenes. -16 LUFS is the level templates mix against.
//
// This is a TWO-PASS loudnorm on purpose. Single-pass loudnorm is a dynamic
// processor: it rides the gain, so during pauses it pulls the clip's noise
// floor up with it and the cloned voice ends up sitting on audible hiss.
// Measuring first and then applying with linear=true gives ONE static gain —
// the noise floor moves up exactly by that gain and never gets pumped.
const LUFS = -16;
const TP = -1.5;
const LRA = 11;
const PRE = "highpass=f=75"; // room rumble the clone models sometimes emit

const measure = async (file) => {
  const { stderr } = await run("ffmpeg", ["-v", "info", "-i", file,
    "-af", `${PRE},loudnorm=I=${LUFS}:TP=${TP}:LRA=${LRA}:print_format=json`,
    "-f", "null", "-"], { maxBuffer: 16 * 1024 * 1024 });
  const json = stderr.slice(stderr.lastIndexOf("{"), stderr.lastIndexOf("}") + 1);
  return JSON.parse(json);
};

const normalise = async (file) => {
  const tmp = `${file}.norm.mp3`;
  try {
    const m = await measure(file);
    await run("ffmpeg", ["-v", "error", "-y", "-i", file,
      "-af", [
        PRE,
        `loudnorm=I=${LUFS}:TP=${TP}:LRA=${LRA}`
          + `:measured_I=${m.input_i}:measured_TP=${m.input_tp}`
          + `:measured_LRA=${m.input_lra}:measured_thresh=${m.input_thresh}`
          + `:offset=${m.target_offset}:linear=true`,
      ].join(","),
      "-c:a", "libmp3lame", "-q:a", "2", tmp]);
  } catch (error) {
    await unlink(tmp).catch(() => {});
    process.stdout.write(`  (skipped loudness pass: ${error.code ?? error.message})\n`);
    return false;
  }
  await rename(tmp, file);
  return true;
};

// Measured in seconds at 3 decimals — one frame at 30fps is 33ms, so this is
// two orders of magnitude finer than anything visible.
const probeDuration = async (file) => {
  const { stdout } = await run("ffprobe", ["-v", "error",
    "-show_entries", "format=duration", "-of", "csv=p=0", file]);
  return Math.round(parseFloat(stdout.trim()) * 1000) / 1000;
};

const writeDurations = async (modulePath, id, durations) => {
  const body = Object.entries(durations)
    .map(([name, seconds]) => `  "${name}": ${seconds},`)
    .join("\n");
  await mkdir(path.dirname(modulePath), { recursive: true });
  await writeFile(
    modulePath,
    `// Generated by scripts/gen-voiceover.mjs — do not edit by hand.\n` +
      `// Measured mp3 durations in seconds, before VO_RATE playback scaling.\n` +
      `// Regenerate: npm run voiceover -- scripts/voiceover/${id}.json --durations-only\n` +
      `export const DURATIONS = {\n${body}\n} as const;\n`,
  );
};

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const flags = new Set(argv.filter((a) => a.startsWith("--")));
const positional = argv.filter((a) => !a.startsWith("--"));
const manifestPath = positional[0];
const envPath = positional[1] ?? path.resolve(root, "../../.env");
const durationsOnly = flags.has("--durations-only");
// Re-levels clips that were synthesised before the loudness pass existed.
// Overwrites the mp3s in place, so it is opt-in.
const normaliseOnly = flags.has("--normalize-only");

if (!manifestPath) {
  throw new Error(
    "Usage: node gen-voiceover.mjs <manifest.json> [env-path] [--durations-only]",
  );
}

const manifest = JSON.parse(await readFile(path.resolve(manifestPath), "utf8"));
const outputDir = path.resolve(root, manifest.outDir);
await mkdir(outputDir, { recursive: true });

// The template id is the voiceover folder name unless the manifest overrides
// where the generated durations module lands.
const templateId = manifest.templateId ?? path.basename(manifest.outDir);
const durationsModule = path.resolve(
  root,
  manifest.durationsModule ?? `src/templates/${templateId}/durations.ts`,
);

if (normaliseOnly) {
  for (const [name] of manifest.lines) {
    const file = path.join(outputDir, `${name}.mp3`);
    const levelled = await normalise(file);
    process.stdout.write(
      `Levelled ${path.relative(root, file)}${levelled ? ` @ ${LUFS} LUFS` : " (failed)"}\n`,
    );
  }
} else if (!durationsOnly) {
  const apiKey =
    process.env.ELEVENLABS_API_KEY ??
    (await readFile(envPath, "utf8"))
      .split(/\r?\n/)
      .find((line) => line.startsWith("ELEVENLABS_API_KEY="))
      ?.slice("ELEVENLABS_API_KEY=".length)
      .trim()
      .replace(/^['"]|['"]$/g, "");

  if (!apiKey) throw new Error(`ELEVENLABS_API_KEY not found in env or ${envPath}`);

  for (const [name, text] of manifest.lines) {
    const response = await fetch(
      `https://api.elevenlabs.io/v1/text-to-speech/${manifest.voiceId}`,
      {
        method: "POST",
        headers: {
          "xi-api-key": apiKey,
          "Content-Type": "application/json",
          Accept: "audio/mpeg",
        },
        body: JSON.stringify({
          text,
          model_id: manifest.modelId ?? "eleven_multilingual_v2",
          voice_settings: manifest.voiceSettings,
        }),
      },
    );

    if (!response.ok) {
      throw new Error(
        `ElevenLabs failed for ${name}: ${response.status} ${await response.text()}`,
      );
    }

    const file = path.join(outputDir, `${name}.mp3`);
    await writeFile(file, Buffer.from(await response.arrayBuffer()));
    const levelled = await normalise(file);
    process.stdout.write(
      `Generated ${path.relative(root, file)}${levelled ? ` @ ${LUFS} LUFS` : ""}\n`,
    );
  }
}

const durations = {};
for (const [name] of manifest.lines) {
  durations[name] = await probeDuration(path.join(outputDir, `${name}.mp3`));
}

await writeDurations(durationsModule, templateId, durations);
process.stdout.write(
  `Measured ${manifest.lines.length} clips → ${path.relative(root, durationsModule)}\n`,
);
